export const PEAK_ASSETS: readonly PeakAsset[] = PEAK_ROWS.map(
  ([terrain, tier, index, w, h]) => ({
    key: `peak-${terrain}-${tier}-${index}`,
    path: `assets/terrain/peaks/${terrain}/${tier}-${index}.png`,
    w,
    h,
    category: "peak",
    terrain,
    tier,
    index,
  }),
);

/** The peaks of one ground. */
export function peaksOf(terrain: GroundTerrain): readonly PeakAsset[] {
  const family = GROUND_FAMILY[terrain];
  return PEAK_ASSETS.filter((peak) => peak.terrain === family);
}
