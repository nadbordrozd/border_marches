/** Every v0.2 faction creature, keyed by id. */
export const FACTION_CREATURES: Readonly<
  Partial<Record<CreatureId, CreatureDef>>
> = Object.fromEntries(
  [
    ...HUMAN_CREATURES,
    ...UNDEAD_CREATURES,
    ...GOBLIN_CREATURES,
    ...CANDY_CREATURES,
    ...DWARVES_CREATURES,
  ].map((c) => [c.id, c]),
);

/** A faction's roster in tier order. */
export function rosterOf(faction: string): readonly CreatureDef[] {
  switch (faction) {
    case "humans":
      return HUMAN_CREATURES;
    case "undead":
      return UNDEAD_CREATURES;
    case "goblins":
      return GOBLIN_CREATURES;
    case "candy":
      return CANDY_CREATURES;
    case "dwarves":
      return DWARVES_CREATURES;
    default:
      return [];
  }
}
