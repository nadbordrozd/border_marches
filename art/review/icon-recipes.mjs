const byId = new Map();
for (const [set, id, seed, things, extra = {}] of RECIPES) {
  const file = `art/sets/${set}/recipes.json`;
  const doc = byId.get(file) ?? JSON.parse(fs.readFileSync(file, "utf8"));
  byId.set(file, doc);
  if (doc.recipes.some((r) => r.id === id)) continue;
  doc.recipes.push({
    id,
    concept: things.map(([cid]) => cid).join(" "),
    width: 32,
    height: 32,
    seed,
    covers: things.map(([cid]) => cid),
    subject: mixed(things),
    ...extra,
  });
}
for (const [file, doc] of byId) fs.writeFileSync(file, `${JSON.stringify(doc, null, 2)}\n`);
